-- 限流计数器表。
--
-- ═══════════════════════════════════════════════════════════════════
-- 为什么限流需要一张表（而不是用已有的读缓存）
-- ═══════════════════════════════════════════════════════════════════
-- 项目里的公开读缓存（`unstable_cache` / Vercel Data Cache）解决的是
-- 「同一份查询结果被重复计算」—— 它是**只读穿透**语义：缓存一份值，失效了重算。
-- 它**没有原子自增**，你没法对它说「这个 key 加一」。
--
-- 而限流需要的是**可变、原子、跨实例共享**的计数器：多个函数实例同时 INC
-- 同一个 key，必须得到一致的结果。这是两类完全不同的东西。
--
-- 不用进程内 Map 的原因很直接：Vercel 上同时存活的实例数不可预测，
-- 进程内计数的实际配额 = 设定值 × 实例数，对「防刷」只能算提高门槛。
--
-- 不用 Redis（Upstash）的原因：本项目已经有 Postgres，用它零新增服务、
-- 零新增凭据、少一个可用性依赖。代价是每个被限流的写请求多一次 upsert ——
-- 而被限流的接口（评论发表、评论点赞、浏览量上报）本来就是写接口，
-- 边际成本只是「多一条小语句」。
--
-- ═══════════════════════════════════════════════════════════════════
-- 表设计
-- ═══════════════════════════════════════════════════════════════════
-- · `key` 作主键 —— 一行代表一个限流维度（如 `comment-create:burst:1.2.3.4`）。
--   行数上界 = 「有行为的不同 IP 数」，不是请求数。
-- · `window_start` + `count` 实现**固定窗口**：跨窗口时计数重置为 1。
--   相比滑动窗口的取舍：边界处最坏可通过 2× 配额，换来的是单条语句原子完成
--   （`INSERT ... ON CONFLICT DO UPDATE ... RETURNING`），无需读-改-写两步。
--   对「防刷」这个目的完全够用。
-- · `window_start` 上的索引供 rate-limit.ts 的低频清理扫过期行用。
-- ═══════════════════════════════════════════════════════════════════

CREATE TABLE "rate_limit" (
    "key" VARCHAR(255) NOT NULL,
    "count" INTEGER NOT NULL DEFAULT 0,
    "window_start" TIMESTAMPTZ(3) NOT NULL,

    CONSTRAINT "rate_limit_pkey" PRIMARY KEY ("key")
);

CREATE INDEX "rate_limit_window_start_idx" ON "rate_limit"("window_start");
